def _say(console: Console, text: str, style: str = "") -> None:
    console.print(Text(text, style=style))  # Text: a reply or a checker's error is not console markup


def _ci(ci: list[float] | tuple[float, float]) -> str:
    return f"[{ci[0]:.0%}, {ci[1]:.0%}]"


def _plural(k: int, word: str) -> str:
    return f"{k:,} {word}" + ("" if k == 1 else "es" if word.endswith("sh") else "s")


def _counts(d: dict[str, int], k: int = 6) -> str:
    items = list(d.items())
    return ", ".join(f"{key} ({n})" for key, n in items[:k]) + (f", {len(items) - k} more" if len(items) > k else "")


def _reply(s: str, n: int = 120) -> str:
    """A reply on one line. A long one keeps both ends, since the answer is often the last thing in it."""
    if not s.strip():
        return "(an empty reply)" if not s else "(spaces and newlines only)"
    s = re.sub(r"^ +| +$", lambda m: "␣" * len(m.group()), s.strip("\n"))  # spaces at the ends may be what is being tested
    s = "".join(ch if ch.isprintable() else " " for ch in re.sub(r"\s*\n\s*", " ⏎ ", s))
    return s if len(s) <= n else f"{s[:2 * n // 3].rstrip()} … {s[-n // 3:].lstrip()}"


def _code(s: str) -> str:
    """Inline Markdown code, whatever backticks the text holds."""
    ticks = "`" * (max(map(len, re.findall(r"`+", s)), default=0) + 1)
    return f"{ticks} {s} {ticks}" if "`" in s else f"{ticks}{s}{ticks}"


def _row_of(f: dict[str, Any]) -> str | None:
    """The summary row a finding belongs to; None for failed calls, which go under Runs reliably."""
    return f["category"] if f["category"] in ROWS else None


def _from_python(result: AuditResult) -> bool:
    """A function handed to the Python API: it has no path, so nothing outside this process can load it again."""
    return result.spec.get("kind") == "function" and not result.spec.get("path")


# --- what the terminal and report.md both say ------------------------------------------------------------------------

def direct_scoring_line(meta: dict[str, Any]) -> str | None:
    """A report scored outside the environment's rollout says so: its findings may describe that call, not a real run."""
    if meta.get("scoring_path") != "direct":
        return None
    return (f"Scored by a direct rubric call, not through the environment's rollout ({meta.get('scoring_path_reason')}). "
            "The rewards get the same reply, answer and info; the state has no trajectory, and an empty reply stays an "
            "empty message, so a reward that reads those can score differently in a real run.")


def no_discrimination_line(c: Contract, m: dict[str, Any]) -> str:
    """Why nothing can be claimed when reference answers do not separate from wrong answers: says which case it is."""
    case, above = m["discrimination"]["case"], m["above_gold"]
    where = f"{c.wrong_checked} rows where the reference answer is accepted"
    same = (f"Reference answers and wrong answers score the same on {c.wrong_same} of the {where} (mean {c.gold_mean:.3g} "
            f"and {c.wrong_mean:.3g}).")
    wrong = f"wrong answers scored strictly above the reference answer on {c.wrong_above} of the {where}"
    check = "A person needs to check how the reference answer is delivered to the checker"
    if case == OUTRANKS:
        parts = [f"{above['k']} of {above['n']} replies that should earn nothing scored strictly above the reference "
                 f"answer on the same row ({_counts(above['probes'])})"] if above["k"] else []
        return (f"Non-answers outrank the reference answer: {'; '.join(parts + ([wrong] if c.wrong_above else []))}. {same} "
                f"{check}; apart from the replies above it, nothing below says whether an answer is right.")
    same += f" In the same calls, {wrong}." if c.wrong_above else ""
    if case == FORMAT_ONLY:
        return (f"Format-only reward: any answer in the right format earns the reference answer's score, and the reference "
                f"answer in other formats earns less. {same} Nothing below says whether an answer is right.")
    return f"{same} {check}; nothing below says whether an answer is right."


def _verdict(result: AuditResult) -> str:
    high, medium = (sum(d["severity"] == s for d in result.defects) for s in SERIOUS)
    found = f"problems found ({high} high, {medium} medium)" if high + medium else ""
    if result.contract.no_discrimination:
        return f"{found}; the rates could not be measured" if found else "the rates could not be measured"
    if found:
        return found
    return "no serious problems found" if result.defects or not _reliability(result)[0] else "no problems found"


def _run_line(result: AuditResult, *, name: bool = True) -> str:
    return " · ".join([f"rewardaudit {result.version}", *([result.env_name] if name else []),
                       f"{len(result.tasks):,} of {result.n_rows:,} rows (seed {result.config.seed})",
                       f"{result.meta.get('checker_calls', 0):,} calls", f"{result.elapsed_s:.0f} s"])


def _top_lines(result: AuditResult) -> list[str]:
    """What changes how every number below is read, so it comes before them."""
    c, meta = result.contract, result.meta
    pin = meta.get("verifiers_pin")  # findings hold on the verifiers they were measured on
    lines = [f"Measured on {pin}, not on the verifiers a fresh install of this package gets."] if pin else []
    lines += [line] if (line := direct_scoring_line(meta)) else []
    flag = "answer_field=True" if _from_python(result) else "--answer-field"
    whole_answer = WHOLE_ANSWER_LINE + (f" This was stated with {flag}, not inferred from the probes." if result.config.answer_field else "")
    return lines + ([no_discrimination_line(c, result.metrics)] if c.no_discrimination else
                    [WHOLE_REPLY_LINE] if c.whole_reply_similarity else
                    [whole_answer] if result.metrics.get("compares_whole_reply") else [])


def _formats(result: AuditResult) -> list[str]:
    """The accepted formats on a real reference answer, … for reasoning: the one the probes used, then plain ones."""
    c = result.contract
    answer = next((t.answer for t in result.tasks if c.self_pass.get(t.id)), "")
    answer = answer if answer and len(answer) <= 24 and "\n" not in answer else "ANSWER"
    texts = {w: _reply(wrapper_fn(w)(answer).replace(REASONING.strip(), "…")) for w in c.accepted}
    return [texts[w] for w in sorted(c.accepted, key=lambda w: (w != c.primary, "…" in texts[w]))]


def _notes(result: AuditResult) -> list[str]:
    """Plain sentences below the summary, each only when it applies."""
    c, formats = result.contract, _formats(result)
    line = f"Reference answers accepted on {c.self_pass_rate:.0%} of rows."
    if formats:
        line += f" Replies were sent in the format {formats[0]}" + (f", one of {len(formats)} it accepts." if len(formats) > 1 else ".")
    if c.self_pass_rate < 1.0:
        n, err = len(c.self_pass), result.metrics["robustness"].get("gold_error_example")
        parts = ", ".join(f"{v} {SELF_FAIL.get(r, r)}" for r, v in c.to_dict()["self_fail_reasons"].items())
        line += f" Rejected in every format tried on {n - sum(c.self_pass.values())} of {n} rows ({parts})."
        line += f" The checker's error on a reference answer: {short_error(err)}" if err else ""
    out = [line]
    if c.signal_keys and len([w for w in result.meta.get("reward_weights") or [] if w]) != 1:
        out.append(f"The score has several parts. Whether an answer is right was judged on {' + '.join(c.signal_keys)}, "
                   "the parts that separate reference answers from wrong ones.")
    h = next(h for h in result.metrics["head"] if h["key"] == "non_solving_accepted")
    if h["n"] and h["value"] > 0 and not h.get("above_floor") and h.get("floor"):
        out.append(f"A fixed answer would be right on {h['floor']:.0%} of rows, so a rate up to that on non-answers says "
                   "nothing about the checker.")
    return out


def _reliability(result: AuditResult) -> tuple[bool, str, int, int]:
    """(all well, that in a phrase, calls that returned no score, calls looked at)."""
    rb, d = result.metrics["robustness"], result.determinism
    calls = rb["n_calls"] + rb.get("n_gold_calls", 0)
    ex, to, cr, net = rb["exceptions"], rb["timeouts"], rb["crashes"], rb["network"]
    errors, timeouts, crashes, attempts = (g["count"] + g["gold"] for g in (ex, to, cr, net))
    types = Counter(ex["by_type"]) + Counter(ex["gold_by_type"])
    top = f" ({'mostly ' if len(types) > 1 else ''}{types.most_common(1)[0][0]})" if types else ""
    parts = [text for k, text in ((errors, _plural(errors, "error") + top), (timeouts, _plural(timeouts, "timeout")),
                                  (crashes, _plural(crashes, "crash")), (attempts, _plural(attempts, "network attempt"))) if k]
    gold = ex["gold"] + to["gold"] + cr["gold"] + net["gold"]
    on_gold = f", {gold:,} of them on reference answers" if gold else ""
    phrases = [f"{', '.join(parts)} in {calls:,} calls{on_gold}"] if parts else []
    if not d["deterministic"]:
        phrases.append(f"the same reply got different scores on {len(d['inconsistent_tasks'])} of {d['checked']} rows")
    phrase = "; ".join(phrases) or f"no errors, timeouts or crashes in {calls:,} calls"
    return not phrases, phrase, errors + timeouts + crashes, calls


def _summary(result: AuditResult) -> list[tuple[str, str, str, str, int, bool]]:
    """(label, yes or no, rate, interval, calls, whether the word is bad news) for each row."""
    heads = {h["key"]: h for h in result.metrics["head"]}
    flagged = {_row_of(f) for f in result.findings if f["severity"] in SERIOUS}
    flagged |= {key for key, h in heads.items() if h.get("severity") in SERIOUS}
    rows = []
    for key, (label, *_) in ROWS.items():
        h, yes = heads[key], key in flagged
        if h["n"] and not h.get("not_measured"):
            rows.append((label, "yes" if yes else "no", f"{h['value']:.0%}", _ci(h["ci"]), h["n"], yes))
        else:  # never a plain "no": nothing was measured, though a finding may still stand
            rows.append((label, "yes" if yes else "", "see Defects" if yes else "not measured", "", 0, yes))
    ok, _, failed, calls = _reliability(result)
    return [*rows, (RELIABLE_ROW, "yes" if ok else "no", f"{failed / calls if calls else 0:.0%} of calls failed",
                    _ci(wilson(failed, calls)), calls, not ok)]


def _evidence_text(d: dict[str, Any]) -> str:
    """The probes behind a defect and their rates."""
    items = [f"{e['probe_id']} {e['rate']:.0%}" for e in d["evidence"]]
    return ", ".join(items[:MAX_EVIDENCE]) + (f", {len(items) - MAX_EVIDENCE} more" if len(items) > MAX_EVIDENCE else "")


def _score(s: float | None) -> str:
    return "no score" if s is None else str(round(s, 3))


def _confirmation_text(c: dict[str, Any], quote: Callable[[str], str] = str, n: int = 120) -> str:
    """A high defect's example sent again, and the shortest reply cut from it that is still accepted."""
    scores = [_score(s) for s in c["resends"]]
    text = f"Sent {len(scores)} more times: " + (f"{scores[0]} each." if len(set(scores)) == 1 else f"{', '.join(scores)}.")
    if short := c.get("shortest_accepted"):
        text += f" Shortest reply still accepted ({_score(short['score'])}): {quote(_reply(short['completion'], n))}"
    return text


def _issue_text(i: dict[str, Any]) -> str:
    parts = [_plural(i["count"], "row") if i.get("tasks") else "", i.get("note", "")]
    return i["name"] + (f" ({'; '.join(x for x in parts if x)})" if any(parts) else "")


# --- terminal --------------------------------------------------------------------------------------------------------

def _grid() -> Table:
    t = Table.grid(padding=(0, 2))
    t.add_column(no_wrap=True)
    t.add_column(no_wrap=True)
    t.add_column(overflow="fold")
    return t


def _print_summary(result: AuditResult, console: Console) -> None:
    t, phrase = _grid(), _reliability(result)[1]
    for label, word, rate, ci, _, bad in _summary(result):
        body = phrase if label == RELIABLE_ROW else f"{rate:>4}  {ci}" if ci else rate
        t.add_row(Text(label), Text(word, style="red" if bad else "green"), Text(body))
    console.print(Padding(t, (0, 0, 1, 2), expand=False))
    if any(h["n"] and not h.get("not_measured") for h in result.metrics["head"]):
        _say(console, "Rates are shares of calls, with 95% intervals. Yes on the first five rows: a high or medium problem.\n", "dim")


def _print_defects(defects: list[dict[str, Any]], console: Console) -> None:
    """One line each: severity, name, the probes behind it. A serious defect adds a line with an example."""
    t = _grid()
    for d in defects:
        t.add_row(Text(d["severity"].upper(), style=SEV_STYLE[d["severity"]]), Text(d["id"]),
                  Text.assemble(d["name"], (f"  {_evidence_text(d)}", "dim")))
        if d["severity"] in SERIOUS and d["example"]:
            t.add_row("", "", Text(_reply(d["example"]["completion"], 60), style="dim"))
        if d.get("confirmation"):
            t.add_row("", "", Text(_confirmation_text(d["confirmation"], n=40), style="dim"))
    console.print(Padding(t, (0, 0, 0, 2), expand=False))


def _print_findings(findings: list[dict[str, Any]], console: Console) -> None:
    t = _grid()
    t.add_column(no_wrap=True, justify="right")
    for f in findings:
        t.add_row(Text(f["severity"].upper(), style=SEV_STYLE[f["severity"]]), Text(f["probe_id"]), Text(f["name"]),
                  Text(f"{f['rate']:.0%}"))
        details = [_reply(f["example"]["completion"])] if f.get("example") else []
        details += [f["note"]] if f.get("note") else []
        details += [f"95% interval {_ci(f['ci'])}, {f['n']:,} {'rows' if f.get('unit') == 'tasks' else 'calls'}"]
        for line in details:
            t.add_row("", "", Text(line, style="dim"), "")
    console.print(Padding(t, (0, 0, 0, 2), expand=False))


def render_terminal(result: AuditResult, console: Console | None = None, *, full: bool = False,
                    out: str | Path | None = None) -> None:
    """`out`: where report.md was saved, if it was."""
    console = console or Console()
    findings, withheld = result.findings, result.metrics["withheld_findings"]
    _say(console, _run_line(result) + "\n", "bold")
    verdict = _verdict(result)
    _say(console, f"Result: {verdict}\n", "bold green" if verdict.startswith("no ") else "bold red")
    for line in _top_lines(result):
        _say(console, line + "\n", "yellow")
    _print_summary(result, console)
    for line in _notes(result):
        _say(console, line)
    if full and result.contract.accepted:
        _say(console, "Accepted formats (… stands for reasoning):")
        for text in _formats(result):
            _say(console, f"  {text}")
    console.print()
    if result.defects:
        _say(console, f"Defects ({len(result.defects)})", "bold")
        _print_defects(result.defects, console)
    elif not withheld:
        _say(console, "No defects.", "green")
    if withheld:
        _say(console, f"Not counted, for the reason above: {_plural(len(withheld), 'more finding')} (see report.json).", "dim")
    console.print()
    if full and findings:
        _say(console, f"Findings ({len(findings)})", "bold")
        _print_findings(findings, console)
        console.print()
    for text in [_issue_text(i) for i in result.dataset_issues] or ["no issues"]:
        _say(console, f"Dataset: {text}")
    console.print()
    if findings and not full:
        _say(console, f"{'full=True' if _from_python(result) else '--full'} prints the {_plural(len(findings), 'finding')} behind this, one per probe.", "dim")
    files = "report.md and report.json" if _from_python(result) else "report.md, report.json and repro.py"
    if out:
        console.print(Text(f"Saved {files} in {Path(out).parent}", style="dim"), soft_wrap=True)
    else:
        _say(console, f"result.save(DIR) writes {files}." if _from_python(result) else f"Add --out DIR to save {files}.", "dim")


