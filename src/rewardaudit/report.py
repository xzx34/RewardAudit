def advice(result: AuditResult) -> list[tuple[str, list[str]]]:
    """For each kind of finding, what the checker did and what a sound one does, plus the probes behind it. This describes
    how the checker scored the replies, since its code is never read."""
    out: list[tuple[str, list[str]]] = []
    c = result.contract
    if c.no_discrimination:
        out.append((f"**Reference answers not separated from wrong answers.** {no_discrimination_line(c, result.metrics)} A "
                    "sound checker scores the reference answer above a wrong one.", []))
    if c.self_pass_rate < 1.0:
        out.append(("**Reference answers rejected.** Some of the dataset's own reference answers got no full score in any "
                    "format tried. A sound checker accepts the reference answer, at least in the format the prompt asks for.", []))
    for key, (_, title, meaning, sound) in ROWS.items():
        fs = [f for f in result.findings if _row_of(f) == key]
        verb = "rejected" if key == "right_rejected" else "accepted"
        items = [f"{f['probe_id']} {f['name']}: {'scored above the reference answer' if f.get('above_gold') else verb} on "
                 f"{f['rate']:.0%} of {'rows' if f.get('unit') == 'tasks' else 'calls'} ({f['severity']})" for f in fs[:6]]
        items += [f"{len(fs) - 6} more under Findings"] if len(fs) > 6 else []
        out += [(f"**{title}.** {meaning} {sound}", items)] if fs else []
    partial = next(h for h in result.metrics["head"] if h["key"] == "wrong_partial")
    if partial.get("severity") in SERIOUS:
        _, title, meaning, sound = ROWS["wrong_partial"]
        out.append((f"**{title}.** {meaning} {sound}", [f"{partial['value']:.0%} of calls: {partial['detail']}"]))
    ok, phrase, *_ = _reliability(result)
    if not ok:
        out.append((f"**Reliability.** {phrase[0].upper()}{phrase[1:]}. A sound checker returns a score for every reply (zero "
                    "for one it cannot parse) well within the time limit, needs no network, and gives the same reply the "
                    "same score.", []))
    return out


def _example_scores(c: Contract, ex: dict[str, Any]) -> str:
    """The scores beside an example; where the score has parts, the total and those parts, for the reply and the reference answer."""
    total = ex["verdict"]["score"]
    if not c.signal_keys or ex["task_id"] not in c.gold_total:
        return f"score {total}"
    parts, judged = sum((ex["verdict"].get("sub_scores") or {}).get(k, 0.0) for k in c.signal_keys), " + ".join(c.signal_keys)
    if ex["probe_id"] == REJECTED_GOLD_ID:  # the reply is the reference answer
        return f"total {total:.3g}; on {judged} {parts:.3g}"
    return (f"this reply's total {total:.3g}, the reference answer's total on this row {c.gold_total[ex['task_id']]:.3g}; on "
            f"{judged} {parts:.3g} and {c.gold_score[ex['task_id']]:.3g}")


def _md_finding(f: dict[str, Any], result: AuditResult) -> list[str]:
    key = _row_of(f)
    meaning = (f["meaning"] if f.get("meaning")
               else "A reply that should earn nothing scored above the reference answer on the same row." if f.get("above_gold")
               else "The checker treats the dataset's own reference answer like a wrong one, in every format tried."
               if f["probe_id"] == REJECTED_GOLD_ID else ROWS[key][2] if key else "The checker returned no score on these replies.")
    over = f"{f['n']:,} rows" if f.get("unit") == "tasks" else f"{f['n']:,} calls on {f['n_tasks']:,} rows"
    L = [f"### {f['severity'].upper()}: {f['probe_id']} {f['name']}", "",
         f"{meaning} Rate {f['rate']:.0%} of {over}, 95% interval {_ci(f['ci'])}.", ""]
    L += [f["note"][0].upper() + f["note"][1:], ""] if f.get("note") else []
    ex = f.get("example")
    if ex:
        gold = next((t.answer for t in result.tasks if t.id == ex["task_id"]), "")
        body = ex["completion"][:1500].replace("\x00", "␀") if ex["completion"].strip() else _reply(ex["completion"])
        fence = "`````" if "```" in body else "```"
        L += [f"Example (row {_code(ex['task_id'])}, reference answer {_code(_reply(gold, 60))}, "
              f"{_example_scores(result.contract, ex)}):", "", fence, body, fence, ""]
    return L


def _md_defects(result: AuditResult) -> list[str]:
    L = ["## Defects", ""]
    L += [] if result.defects else ["None.", ""]
    for d in result.defects:
        evidence = ", ".join(f"{e['probe_id']} {e['rate']:.0%} of {e['n']:,} {'rows' if e['unit'] == 'tasks' else 'calls'}" for e in d["evidence"])
        example = f" Example: {_code(_reply(d['example']['completion']))}." if d["example"] else ""
        L.append(f"- **{d['severity'].upper()}: {d['id']} {d['name']}.** {d['explanation']} Evidence: {evidence}.{example}")
        L += [f"  - {_confirmation_text(d['confirmation'], _code)}"] if d.get("confirmation") else []
    return L + ([""] if result.defects else [])


def _md_reliability(result: AuditResult) -> list[str]:
    ok, phrase, *_ = _reliability(result)
    rb, d = result.metrics["robustness"], result.determinism
    if ok:
        return [f"Every call returned a score: {phrase}, and no network attempts. A reference answer and a reply with no answer, "
                f"each sent several times, got the same score each time, on all {d['checked']} rows checked.", ""]
    L = [f"{phrase[0].upper()}{phrase[1:]}.", ""]
    for title, key in (("Errors", "exceptions"), ("Timeouts", "timeouts"), ("Crashes", "crashes"), ("Network attempts", "network")):
        g = rb[key]
        if g["count"] or g["gold"]:
            probes = f" (probes: {_counts(g['probes'])})" if g["probes"] else ""
            L.append(f"- **{title}**: {g['count']:,} of {rb['n_calls']:,} probe calls{probes} and {g['gold']:,} of "
                     f"{rb.get('n_gold_calls', 0):,} calls with a reference answer. {g.get('note', '')}".rstrip())
        ex = g["example"]
        if ex:
            L.append(f"  - Example: probe {ex['probe_id']}, row {_code(ex['task_id'])}, reply {_code(_reply(ex['completion']))}"
                     + (f", error {_code(short_error(ex['error']))}" if ex.get("error") else ""))
    if not d["deterministic"]:
        L.append(f"- **Different scores for the same reply**: rows {', '.join(d['inconsistent_tasks'])}, with the reference answer or a reply with no answer sent several times.")
    return L + [""]


def _md_how_run(result: AuditResult) -> list[str]:
    spec, meta, cfg = result.spec, result.meta, result.config
    checker = f"`{result.env_name}`" + (f" from `{spec['path']}`" if spec.get("path") else "")
    checker += f", called in the `{meta['style']}` style" if meta.get("style") else ""
    data = str(spec.get("dataset") or "")
    known = data.startswith("hf:") or (data and Path(data).exists())  # rows handed over in memory went to a temporary file
    data = f"`{data}`" if known else "rows passed in memory" if data else "the checker's own"
    L = [f"- Checker: {checker}", f"- Dataset: {data}, {result.n_rows:,} rows",
         f"- Sample: {len(result.tasks):,} rows drawn at random, seed {cfg.seed}", f"- Timeout: {cfg.timeout_s:g} s per call",
         f"- Workers: {cfg.workers}"]
    L += [f"- Probe families: {', '.join(cfg.families)}"] if cfg.families else []
    L += [f"- Framework: {meta['framework']}"] if meta.get("framework") else []
    return L + ([] if _from_python(result) else ["- `repro.py`, next to this report, re-scores the reply behind each finding"])


def render_markdown(result: AuditResult) -> str:
    findings, withheld = result.findings, result.metrics["withheld_findings"]
    L = [f"# rewardaudit report: {result.env_name}", "", _run_line(result, name=False), ""]
    for line in _top_lines(result):
        L += [line, ""]

    L += ["## Summary", "", f"**Result: {_verdict(result)}**", "",
          "| Check | Result | Rate | 95% interval | Calls |", "|---|---|---|---|---|"]
    L += [f"| {label} | {word} | {rate} | {ci} | {n:,} |" for label, word, rate, ci, n, _ in _summary(result)]
    best = next(h for h in result.metrics["head"] if h["key"] == "non_solving_accepted").get("strategy") or {}
    L += ["", "Rates are shares of calls, and the interval is a 95% Wilson interval. The first five rows say yes when they have a high or "
          "medium problem." + (f" Accepts non-answers is the rate of the best such reply, {best['probe']}, measured on rows other than "
                        "those it was chosen on." if (best.get("confirm") or [0, 0])[1] else ""), ""]
    for line in _notes(result):
        L += [line, ""]
    L += [SEVERAL_TERMS, ""] if len(result.contract.signal_keys or []) > 1 else []

    L += _md_defects(result)
    L += ["## Findings", ""]
    L += [] if findings else ["None that can be claimed." if withheld else "None.", ""]
    for f in findings:
        L += _md_finding(f, result)
    L += [f"Not counted: {_plural(len(withheld), 'more finding')}, since what they would claim does not hold for this checker "
          "(see the top of this report). They are under `withheld_findings` in report.json.", ""] if withheld else []

    L += ["## What to fix", ""]
    tips = advice(result)
    L += [] if tips else ["Nothing: no probe found a reply that the checker scored against what it should earn."]
    for tip, items in tips:
        L += [f"- {tip}", *(f"  - {item}" for item in items)]

    formats = _formats(result)
    L += ["", "## Answer formats", "", "The checker gave reference answers full score in these formats (… stands for reasoning). "
          "The probes used the first." if formats else "The checker gave reference answers full score in no format tried.", ""]
    L += [f"- {_code(text)}" for text in formats[:MAX_FORMATS]]
    L += [f"- and {len(formats) - MAX_FORMATS} more"] if len(formats) > MAX_FORMATS else []

    L += ["", "## Reliability", "", *_md_reliability(result)]

    L += ["## Dataset", "", f"These checks cover all {result.n_rows:,} rows of the dataset, not only the sampled ones.", ""]
    for i in result.dataset_issues:
        rows = ", ".join(" = ".join(x) if isinstance(x, list) else str(x) for x in (i.get("tasks") or [])[:5])
        L.append(f"- **{i['severity']}** {_issue_text(i)}" + (f". For example: {rows}" if rows else ""))
    L += [] if result.dataset_issues else ["No issues."]

    L += ["", "## How this was run", "", *_md_how_run(result)]
    return "\n".join(L) + "\n"


# --- report.json, repro.py -------------------------------------------------------------------------------------------

def write_outputs(result: AuditResult, out_dir: str | Path) -> Path:
    """Write report.md, report.json and, when the checker can be loaded again, repro.py. Returns the path of report.md."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.json").write_text(json.dumps({"schema_version": SCHEMA_VERSION, **result.to_dict()}, indent=1,
                                                ensure_ascii=False, default=str), encoding="utf-8")
    report = out / "report.md"
    report.write_text(render_markdown(result), encoding="utf-8")
    if _from_python(result):
        return report
    tasks = {t.id: t for t in result.tasks}
    cases = [{"probe_id": f["probe_id"], "expect": f["example"]["expect"], "task": tasks[f["example"]["task_id"]].to_dict(),
              "completion": f["example"]["completion"]}
             for f in result.findings if f.get("example") and f["example"]["task_id"] in tasks]
    spec = dict(result.spec)
    target, sep, func = str(spec.get("path") or "").partition(":")
    if target and Path(target).exists():  # so that repro.py runs from any directory
        spec["path"] = f"{Path(target).resolve()}{sep}{func}"
    hub = spec.get("kind") == "verifiers" and "/" in str(spec.get("env"))  # installed into a venv of its own
    pin = result.meta.get("verifiers_pin")
    (out / "repro.py").write_text(REPRO_TEMPLATE.format(
        version=result.version, spec=spec, cases=json.dumps(cases), timeout=result.config.timeout_s,
        imports="from rewardaudit.envs import install_env\n" if hub else "",
        python=f", python=str(install_env(SPEC['env'], verifiers={pin!r})[0])" if hub else ""), encoding="utf-8")
    return report


